export function detectLocale(): Locale {
  const stored = localStorage.getItem("pp_locale");
  if (stored === "de" || stored === "en") return stored;
  return navigator.language.toLowerCase().startsWith("de") ? "de" : "en";
}

type TFn = (key: string, vars?: Record<string, string | number>) => string;
interface I18nCtx {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: TFn;
}

const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(detectLocale);
  const setLocale = useCallback((l: Locale) => {
    localStorage.setItem("pp_locale", l);
    document.documentElement.lang = l;
    setLocaleState(l);
  }, []);
  const t = useCallback<TFn>(
    (key, vars) => {
      let s = resources[locale][key] ?? resources.de[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    [locale],
  );
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

/** Localize an ApiError by its stable `code` (server messages are English/internal — API-09),
 *  falling back to the server message for codes we don't translate. */
export function errorText(err: unknown, t: TFn): string {
  if (err instanceof ApiError) {
    if (err.status >= 500) return t("error.server"); // never show raw 5xx detail
    const key = `error.code.${err.code}`;
    const msg = t(key);
    return msg === key ? t("error.generic") : msg; // unknown code → friendly generic, never raw BE text
  }
  // A non-ApiError means the fetch itself failed — almost always network/offline.
  return t(
    typeof navigator !== "undefined" && !navigator.onLine ? "error.offline" : "error.generic",
  );
}

/** Map a bare error *code* (e.g. from a `?error=` redirect param) to a localized message,
 *  falling back to the friendly generic for codes we don't translate (N21). */
export function codeMessage(code: string, t: TFn): string {
  const key = `error.code.${code}`;
  const msg = t(key);
  return msg === key ? t("error.generic") : msg;
}
